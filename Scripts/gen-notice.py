#!/usr/bin/env python3
"""Regenerate NOTICE.md from the resolved Swift packages. Usage: Scripts/gen-notice.py <checkouts-dir>

<checkouts-dir> is DerivedData's SourcePackages/checkouts after a build, e.g.
build/DerivedData/SourcePackages/checkouts. LINKED is the set the app binary actually links; check it
against the build's Zubi.LinkFileList whenever a package is added or Hummingbird is bumped.
"""
import json, pathlib, sys

LINKED = [
    "hummingbird", "swift-async-algorithms", "swift-atomics", "swift-collections",
    "swift-configuration", "swift-distributed-tracing", "swift-http-types", "swift-log",
    "swift-metrics", "swift-nio", "swift-nio-extras", "swift-nio-transport-services",
    "swift-service-context", "swift-service-lifecycle", "swift-system",
]
EXCEPTION_MARK = "## Runtime Library Exception to the Apache 2.0 License: ##"

root = pathlib.Path(__file__).resolve().parent.parent
checkouts = pathlib.Path(sys.argv[1])
pins = {p["identity"]: p for p in json.loads((root / "Zubi.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved").read_text())["pins"]}

def read(path):
    return path.read_text(encoding="utf-8").strip("\n")

rows, notices, apache, exception = [], [], None, None
for name in LINKED:
    pin = pins[name]
    url = pin["location"].removesuffix(".git")
    license_text = read(checkouts / name / "LICENSE.txt")
    head, _, tail = license_text.partition(EXCEPTION_MARK)
    assert "Apache License" in head and "Version 2.0" in head, f"{name} is no longer Apache-2.0"
    apache = apache or head.strip("\n")
    if tail:
        exception = exception or (EXCEPTION_MARK + tail).strip("\n")
    rows.append(f"| [{name}]({url}) | {pin['state']['version']} | Apache-2.0{' with Runtime Library Exception' if tail else ''} |")
    notice = checkouts / name / "NOTICE.txt"
    if notice.exists():
        notices.append(f"### {name}\n\n```\n{read(notice)}\n```")

llhttp = read(checkouts / "swift-nio/Sources/CNIOLLHTTP/LICENSE")

out = f"""# Third-party notices

Zubi is licensed under the MIT License — see [LICENSE](LICENSE). The app also redistributes the
third-party material recorded below, under the terms stated for each. This file ships inside
`Zubi.app/Contents/Resources`, so the notices travel with the binary as the licences ask.

<!-- Generated by Scripts/gen-notice.py from the resolved packages. Edit the script, not this file. -->

## Swift packages

The HTTP API is served by [Hummingbird](https://github.com/hummingbird-project/hummingbird) on top of
[SwiftNIO](https://github.com/apple/swift-nio). These packages are linked into the app, unmodified:

| Package | Version | License |
| --- | --- | --- |
{chr(10).join(rows)}

Packages Swift Package Manager resolves but the app does not link, such as `swift-nio-ssl`,
`swift-crypto` and `async-http-client`, are not part of the binary and are not listed.

### NOTICE files

Apache License 2.0 §4(d) asks that a redistribution carry the attribution notices in each work's
`NOTICE` file. They are reproduced here as published.

{chr(10).join(notices)}

## llhttp — HTTP/1 parsing

SwiftNIO's `CNIOLLHTTP` module, linked into the app, contains Node.js's
[llhttp](https://github.com/nodejs/llhttp). It is MIT licensed, and its licence requires this notice
to travel with the work:

```
{llhttp}
```

## GitHub mark — `Sources/Assets.xcassets/BrandGitHub.imageset`

The GitHub mark beside the repository link on the About page is a trademark of GitHub, Inc., used
only to label a link to Zubi's own repository. No affiliation or endorsement is implied.

## Apache License 2.0

The terms every package above is licensed under.

```
{apache}
```

```
{exception}
```
"""
(root / "NOTICE.md").write_text(out, encoding="utf-8")
print(f"NOTICE.md: {len(rows)} packages, {len(notices)} NOTICE files")
