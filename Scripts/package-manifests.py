#!/usr/bin/env python3
"""Write the Homebrew formula and Scoop manifest for a CLI release.

Usage: package-manifests.py <version> <checksums.txt> <formula-out.rb> <manifest-out.json>

Both point at the archives release-cli.yml publishes on the cli/v<version> GitHub Release, pinned by the
SHA-256 sums in that release's checksums file, so a package manager installs exactly what CI built.
Standard library only. See docs/release.md.
"""
import json
import pathlib
import sys

REPO = "https://github.com/fa-krug/zubi"
DESCRIPTION = "Read and edit the Reminders, calendars and Notes a Mac running Zubi shares"
HOMEPAGE = "https://zubi.fa-krug.de/"


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    version, checksums, formula_out, manifest_out = sys.argv[1:]
    sums = {}
    for line in pathlib.Path(checksums).read_text().splitlines():
        digest, _, name = line.strip().partition("  ")
        sums[name] = digest

    def asset(platform):
        name = f"zubi_{version}_{platform}"
        archive = name + (".zip" if platform.startswith("windows") else ".tar.gz")
        if archive not in sums:
            sys.exit(f"{archive} is not in {checksums}")
        return name, f"{REPO}/releases/download/cli/v{version}/{archive}", sums[archive]

    _, mac_url, mac_sum = asset("darwin_universal")
    _, x64_url, x64_sum = asset("linux_amd64")
    _, arm_url, arm_sum = asset("linux_arm64")
    # Homebrew on Linux runs on x86-64 and 64-bit ARM only, so the armv7 archive stays a manual download.
    formula = f'''# Generated by Scripts/package-manifests.py for each CLI release. Don't edit by hand.
class Zubi < Formula
  desc "{DESCRIPTION}"
  homepage "{HOMEPAGE}"
  license "MIT"

  # Homebrew only allows a URL inside on_intel/on_arm; the one universal archive serves both.
  on_macos do
    on_intel do
      url "{mac_url}"
      sha256 "{mac_sum}"
    end
    on_arm do
      url "{mac_url}"
      sha256 "{mac_sum}"
    end
  end

  on_linux do
    on_intel do
      url "{x64_url}"
      sha256 "{x64_sum}"
    end
    on_arm do
      url "{arm_url}"
      sha256 "{arm_sum}"
    end
  end

  def install
    bin.install "zubi"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/zubi version")
  end
end
'''
    pathlib.Path(formula_out).write_text(formula)

    architectures = {}
    for scoop_arch, platform in (("64bit", "windows_amd64"), ("arm64", "windows_arm64")):
        name, url, digest = asset(platform)
        architectures[scoop_arch] = {"url": url, "hash": digest, "extract_dir": name}
    manifest = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": HOMEPAGE,
        "license": "MIT",
        "architecture": architectures,
        "bin": "zubi.exe",
        "notes": "Configure it with: zubi config set url http://<your-mac>:8787 and zubi config set key -",
    }
    pathlib.Path(manifest_out).write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {formula_out} and {manifest_out} for {version}")


if __name__ == "__main__":
    main()
